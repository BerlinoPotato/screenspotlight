"""Generate PLAR's single-file edition from the current application sources."""
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def runner_source():
    source = (ROOT / "spotlight.py").read_text(encoding="utf-8")
    emergency = (ROOT / "emergency.py").read_text(encoding="utf-8")
    source = source.replace("from emergency import EmergencyExit", emergency)
    source = source.replace(
        "def app_icon():\n    return QIcon(str(Path(__file__).resolve().with_name(\"screenspotlight.png\")))",
        "def app_icon():\n"
        "    import base64\n"
        "    from PySide6.QtGui import QPixmap\n"
        "    pixmap = QPixmap()\n"
        f"    pixmap.loadFromData(base64.b64decode({base64.b64encode((ROOT / 'screenspotlight.png').read_bytes())!r}))\n"
        "    return QIcon(pixmap)",
    )
    source = source.replace(
        'if __name__ == "__main__":\n    raise SystemExit(main())',
        'if __name__ == "__main__":\n'
        '    if "--check" in sys.argv:\n'
        '        print(f"Screen Spotlight PLAR {APP_VERSION}: Python and PySide6 imports OK")\n'
        '    else:\n'
        '        raise SystemExit(main())',
    )
    return '# Generated by plar/prepare_runner.py; edit spotlight.py instead.\n' + source


def main():
    runner = ROOT / "plar/runner_screen_spotlight.py"
    runner.write_text(runner_source(), encoding="utf-8")
    files = ("spotlight.py", "emergency.py", "screenspotlight.png", "plar/runner_screen_spotlight.py")
    hashes = {name: hashlib.sha256((ROOT / name).read_bytes()).hexdigest() for name in files}
    (ROOT / "plar/snapshot.json").write_text(json.dumps(hashes, indent=2) + "\n", encoding="utf-8")
    print(f"Updated {runner}")


if __name__ == "__main__":
    main()
